"""Write js/media-index.js: every image under assets/ the pages may show.

Artwork is found by record id: assets/<folder>/<id>.<ext>, where the folders
for each record type are listed in js/config.js (types[].folders). Run after
adding or removing images:

    python tools/build_media_index.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXTS = {".webp", ".png", ".jpg", ".jpeg", ".avif"}
files = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "assets").rglob("*")
               if p.suffix.lower() in EXTS and "cover" not in p.parts)
(ROOT / "js" / "media-index.js").write_text(
    "/* Generated by tools/build_media_index.py. Do not edit by hand. */\n"
    f"window.MEDIA_INDEX = {json.dumps(files, indent=1)};\n", encoding="utf-8", newline="\n")
print(f"{len(files)} images indexed")
